export function t(key, vars = {}) {
    const source = dictionary[locale]?.[key] ?? dictionary.en[key] ?? key;
    return String(source).replace(/\{(\w+)\}/g, (_, name) => {
        return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : `{${name}}`;
    });
}

export function localizeText(text) {
    return typeof text === 'string' ? text : String(text);
}

